local H = require('tests.helpers')
H.begin_case()
local path = H.temp_file(string.char(0xAB))
vim.cmd('Hex ' .. vim.fn.fnameescape(path))
local session = H.wait_ready(vim.api.nvim_get_current_buf())
local register = require('hexit.actions').register()
vim.g.clipboard = { name = 'missing', copy = {}, paste = {} }
local ok, err = pcall(vim.cmd, 'HexCopyAs hex +')
assert(not ok and tostring(err):find('system clipboard provider is unavailable', 1, true), tostring(err))
assert(require('hexit.actions').register() == register)
assert(session.cursor.offset == 0)
vim.cmd('HexCopyAs hex "')
assert(vim.wait(2000, function() return vim.fn.getreg('"') == 'AB' end, 10))
H.end_case()
vim.cmd('qa!')
